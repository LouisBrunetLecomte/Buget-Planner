interface Key { re: RegExp; len: number; categories: string[] }
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
function compile(entries: Entry[]): Key[] {
  const keys: Key[] = []
  for (const [cats, words] of entries) {
    const categories = cats.split('|')
    // mots composés : « SUPER U », « BURGER KING »… on garde les groupes connus, puis chaque mot isolé
    for (const kw of splitKeywords(words)) {
      const prefix = kw.endsWith('*'), k = prefix ? kw.slice(0, -1) : kw
      keys.push({ re: new RegExp(`(^| )${esc(k)}${prefix ? '' : '( |$)'}`), len: k.length, categories })
    }
  }
  return keys.sort((a, b) => b.len - a.len)
}
