function splitKeywords(words: string): string[] {
  let rest = ` ${words} `
  const out: string[] = []
  for (const m of [...MULTI].sort((a, b) => b.length - a.length)) {
    const needle = ` ${m} `
    if (rest.includes(needle)) { out.push(m); rest = rest.split(needle).join(' ') }
  }
  return [...out, ...rest.split(' ').filter(Boolean)]
}

const EXP = compile(EXPENSES), INC = compile(INCOME)

/**
 * Catégories probables (de la plus précise à la plus large) d'après l'établissement, ou [] si inconnu.
 * `amount` : signe de l'opération (dépense < 0, revenu > 0).
 */
export function guessCategories(labelNorm: string, amount: number): string[] {
  const keys = amount > 0 ? INC : EXP
  return keys.find((k) => k.re.test(labelNorm))?.categories ?? []
}
